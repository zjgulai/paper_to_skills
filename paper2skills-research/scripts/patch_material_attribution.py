def plan() -> tuple[list[tuple[Path, str, str]], list[str], list[str], list[str]]:
    """返回 (待应用, 已应用, 过期对不上, 明细)。

    ⚠️ **三态必须分开** —— 「补丁该不该再跑一次」与「补丁还有没有效」是两件事，
    合并成一个数就会把「锚点被别的手改没了」读成「早就应用过了」：
    · **待应用**：old 恰好出现一次 ⇒ 还没落盘；
    · **已应用**：old 不再出现、而 new 在 ⇒ 正常终态；
    · **过期**：old、new **都不在** ⇒ 语料被别处改过，这处残留**无人知晓地回来了**。
    """
    todos, applied, stale, detail = [], [], [], []
    for rel, pairs in PATCHES:
        p = CONTRACTS / rel
        if not p.exists():
            stale.append(f"{rel}：文件不存在")
            continue
        text = p.read_text(encoding="utf-8")
        for old, new in pairs:
            n = text.count(old)
            if n == 1:
                todos.append((p, old, new))
                detail.append(f"[待应用] {rel}：{old[:44]}…")
            elif n == 0 and new in text:
                applied.append(f"{rel}：{new[:44]}…")
            elif n == 0:
                stale.append(f"{rel}：old 与 new 都不在 → {old[:48]}…")
            else:
                stale.append(f"{rel}：old 出现 {n} 次（必须恰好 1 次）→ {old[:48]}…")
    return todos, applied, stale, detail


def apply(todos) -> int:
    by_file: dict[Path, list[tuple[str, str]]] = {}
    for p, old, new in todos:
        by_file.setdefault(p, []).append((old, new))
    for p, pairs in by_file.items():
        text = p.read_text(encoding="utf-8")
        for old, new in pairs:
            assert text.count(old) == 1, p
            text = text.replace(old, new)
        p.write_text(text, encoding="utf-8")
    return len(by_file)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="只报告，不落盘")
    ap.add_argument("--apply", action="store_true", help="落盘")
    ap.add_argument("--verbose", action="store_true", help="逐条打印待应用锚点")
    a = ap.parse_args()
    if not (a.check or a.apply):
        ap.error("必须给 --check 或 --apply")

    todos, applied, stale, detail = plan()
    total = sum(len(v) for _, v in PATCHES)
    print(f"# W-67a 材料归属改标补丁 · 共 {total} 处锚点 / {len(PATCHES)} 份文件")
    print(f"  待应用 {len(todos)} · 已应用 {len(applied)} · **过期对不上 {len(stale)}**")
    if a.verbose:
        for x in detail:
            print(f"    {x}")
    if stale:
        print("\n❌ 有锚点既不是「待应用」也不是「已应用」—— 语料被别的手改过，"
              "这处残留可能已经无人知晓地回来了：")
        for x in stale[:20]:
            print(f"    · {x}")
        return 1
    if a.check:
        if todos:
            print("\n⚠️ 仍有待应用锚点；加 --apply 落盘。")
            return 0
        print(f"\n✅ 补丁全部落盘（{len(applied)} 处已应用，0 处待应用，0 处过期）。")
        return 0
    if not todos:
        print("\n✅ 已无待应用锚点（补丁已是终态）。")
        return 0
    n = apply(todos)
    print(f"\n✅ 已改写 {len(todos)} 处 / {n} 份文件（不删一字，只改归属 + 补来源标记）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
